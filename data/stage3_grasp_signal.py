#!/usr/bin/env python
"""Derive the finger open/close signal from geometry, not from Stage 2 contacts.

WHY
---
SONIC's g1_43dof drives its 14 finger joints from a 2-scalar primitive
(`use_finger_primitive` + `use_motion_hand_actions`): -1.0 = open, +1.0 = closed,
thresholded at 0. Those scalars are read straight out of the motion pkl as
`hand_action_left` / `hand_action_right`.

The ones shipped in `grail_chair_ha` are wrong. They are generated by
`grail/retargeting/process.py` from `hoi_data["obj_data"]["obj_contact_points"]`,
and on this clip Stage 2's contact detection reports:

    right_hand   contact f17-94          <- matches the carry
    left_hand    contact f9-11, f90, f99-115  <- MISSES f24-84 entirely

so the left hand is commanded OPEN for the whole carry and CLOSED at f0-10 when
it is 34 cm from the chair. Measured against the retargeted motion, both wrists
sit 9-10 cm from the chair mesh continuously from f20 to f90 - both hands are on
it. The generator is faithful; its input is not.

WHAT THIS DOES
--------------
Closes a hand when its palm is near the object mesh, using the retargeted robot
and the object's own trajectory - the same geometry the physics will see. Then:

  * hysteresis, so a hand that is holding something does not flicker open on a
    single noisy frame (close at `--close`, release only past `--open`);
  * `--anticipate` frames of early closing, because fingers take time to shut
    and a hand that closes on contact has already missed;
  * a minimum hold length, to delete one-frame grasps.

VALIDATION is the point, and it is built in: the object cannot be off its resting
height unless some hand is closed. Frames where the object is raised with both
hands open are reported as violations. A good signal has none.

Usage:
    python data/stage3_grasp_signal.py <motion_lib_dir> [--write] [--object_rest_z auto]
"""
import argparse, glob, os, importlib.util
import numpy as np, joblib, mujoco, trimesh
from scipy.spatial.transform import Rotation as R

_spec = importlib.util.spec_from_file_location(
    "feas", os.path.join(os.path.dirname(os.path.abspath(__file__)),
                         "stage3_mujoco_feasibility.py"))
_feas = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_feas)

PALM = {"left": "left_wrist_yaw_link", "right": "right_wrist_yaw_link"}


def hand_surface(m, d, body_id):
    """World-space points on a hand body's COLLISION SURFACE.

    Measuring from the body ORIGIN is what made the first version of this script
    wrong. wrist_yaw_link's origin sits ~10 cm behind the palm, so during the
    carry the left origin reads 9-10 cm from the chair - "close" under any sane
    threshold - while the palm itself is 8-11 cm away and touching nothing. That
    produced a signal closing the left hand on air for the whole carry, and it
    disagreed with Stage 2's contact annotation, which was correct.
    """
    pts = []
    for g in range(m.ngeom):
        if m.geom_bodyid[g] != body_id or not m.geom_contype[g]:
            continue
        if m.geom_type[g] == mujoco.mjtGeom.mjGEOM_MESH:
            mid = m.geom_dataid[g]
            v = m.mesh_vert[m.mesh_vertadr[mid]:m.mesh_vertadr[mid] + m.mesh_vertnum[mid]]
            pts.append(v @ d.geom_xmat[g].reshape(3, 3).T + d.geom_xpos[g])
        else:
            pts.append(d.geom_xpos[g][None])
    return np.vstack(pts) if pts else None


def object_vertices(motion_dir, O, n_samples=60000):
    """Points sampled ON the object surface, in local frame, at motion-lib scale.

    VERTICES ARE NOT ENOUGH, and using them is what made two earlier readings of
    this clip wrong in opposite directions. These meshes are low-poly - the chair
    is 0.90 m^2 across ~1400 faces - so the nearest VERTEX to a palm resting flat
    on the seat can be 8-11 cm away while the surface is touching. Measured both
    ways at frame 50: nearest vertex says the left palm is 0.096 m from the
    chair (read as "not holding it"), surface sampling says 0.044 m (read as
    "holding it"), and the video shows a two-handed carry.

    Sampling the surface at ~4 mm spacing and querying a KD-tree gives the
    surface distance without needing trimesh's rtree-backed proximity, which is
    not installed here.
    """
    # meta carries object_path=None and object_name="object" on these libs, so
    # neither identifies the mesh. Fall back to the motion-lib directory name,
    # which does ("grail_chair_v2" -> chair).
    meta = glob.glob(f"{motion_dir}/meta/*.pkl")
    path = None
    if meta:
        try:
            path = joblib.load(meta[0]).get("object_path")
        except Exception:
            path = None
    if not path or not os.path.isfile(str(path)):
        names = [O.get("object_name") or "",
                 os.path.basename(motion_dir.rstrip("/")).replace("grail_", "").split("_")[0]]
        path = None
        for name in names:
            if not name or name == "object":
                continue
            for cand in (f"results/generation/mesh/ComAsset/{name}/model.obj",
                         f"data/ComAsset/{name}/model.obj"):
                if os.path.isfile(cand):
                    path = cand
                    break
            if path:
                break
    if not path:
        raise SystemExit(f"could not locate the object mesh for {motion_dir}")
    mesh = trimesh.load(path)
    if isinstance(mesh, trimesh.Scene):
        mesh = mesh.dump(concatenate=True)
    v = np.asarray(mesh.vertices, dtype=float)
    s = np.asarray(O.get("scale", 1.0)).reshape(-1)
    s = s[:3] if s.size >= 3 else np.full(3, float(s[0]))
    mesh.vertices = v * s
    scaled, _ = trimesh.sample.sample_surface(mesh, n_samples)
    scaled = np.asarray(scaled)
    # Guard against a degenerate object pkl. grail_chair_ha ships scale=1.0 and
    # object_name=None, which leaves this chair mesh ~10x oversized with a 2.8 m
    # centroid offset - every palm-to-object distance then comes out far too
    # large and the signal is silently all-open. grail_chair has the real 0.106.
    ext = np.asarray(scaled).max(0) - np.asarray(scaled).min(0)
    if ext.max() > 3.0 or ext.max() < 0.05:
        raise SystemExit(
            f"object scale looks wrong: scale={s}, scaled extents={np.round(ext,3)} m.\n"
            f"  Expected a graspable object (< 3 m). Check {motion_dir}/objects/*.pkl - "
            f"grail_chair_ha's is degenerate; use a lib whose object pkl kept its scale.")
    return scaled, path


def hysteresis(dist, close_t, open_t, anticipate, min_hold):
    """Closed while near; releases only once clearly clear of the object."""
    n = len(dist)
    closed = np.zeros(n, dtype=bool)
    state = False
    for i in range(n):
        if state:
            state = dist[i] < open_t
        else:
            state = dist[i] < close_t
        closed[i] = state
    # shut the hand early - fingers are not instantaneous
    if anticipate > 0:
        out = closed.copy()
        for i in range(n):
            if closed[i]:
                out[max(0, i - anticipate):i] = True
        closed = out
    # drop grasps too short to be real
    i = 0
    while i < n:
        if closed[i]:
            j = i
            while j < n and closed[j]:
                j += 1
            if j - i < min_hold:
                closed[i:j] = False
            i = j
        else:
            i += 1
    return closed


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("motion_dir")
    ap.add_argument("--close", type=float, default=0.06, help="close within this (m)")
    ap.add_argument("--open", type=float, default=0.11, help="release past this (m)")
    ap.add_argument("--anticipate", type=int, default=3, help="frames to close early")
    ap.add_argument("--min_hold", type=int, default=5)
    ap.add_argument("--lift", type=float, default=0.03,
                    help="object counts as supported once this far above its resting z")
    ap.add_argument("--object_dir", default="objects",
                    help="which object subdir to grasp against (objects | objects_basket)")
    ap.add_argument("--suffix", default="",
                    help="write to hand_action_left<suffix> instead, so a clip with "
                         "two manipulated objects can carry a signal for each")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()

    rp = glob.glob(f"{a.motion_dir}/robot/*.pkl")[0]
    data = joblib.load(rp); key = list(data)[0]; M = data[key]
    O = list(joblib.load(glob.glob(f"{a.motion_dir}/{a.object_dir}/*.pkl")[0]).values())[0]

    rt, rr, dof = (np.array(M["root_trans_offset"]), np.array(M["root_rot"]),
                   np.array(M["dof"]))
    op = np.array(O["root_pos"])[:, 0]
    oq = np.array(O["root_quat"])[:, 0]
    if O.get("mesh") and os.path.isfile(str(O["mesh"])):
        import trimesh as _tm
        _m = _tm.load(O["mesh"])
        if isinstance(_m, _tm.Scene):
            _m = _m.dump(concatenate=True)
        V0 = np.asarray(_tm.sample.sample_surface(_m, 60000)[0])
        mesh_path = O["mesh"]
    else:
        V0, mesh_path = object_vertices(a.motion_dir, O)

    m = mujoco.MjModel.from_xml_path(_feas.G1_MJCF)
    d = mujoco.MjData(m)
    B = {h: mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_BODY, n) for h, n in PALM.items()}

    T = len(dof)
    from scipy.spatial import cKDTree
    dist = {h: np.zeros(T) for h in PALM}
    for f in range(T):
        d.qpos[0:3], d.qpos[3:7], d.qpos[7:36] = rt[f], rr[f], dof[f]
        mujoco.mj_forward(m, d)
        Vw = V0 @ R.from_quat(oq[f][[1, 2, 3, 0]]).as_matrix().T + op[f]
        tree = cKDTree(Vw)
        for h in PALM:
            P = hand_surface(m, d, B[h])
            if P is None:
                dist[h][f] = tree.query(d.xpos[B[h]][None])[0].min()
            else:
                dist[h][f] = tree.query(P)[0].min()

    closed = {h: hysteresis(dist[h], a.close, a.open, a.anticipate, a.min_hold)
              for h in PALM}

    # Proximity alone under-triggers: the hand's COLLISION geom is smaller than
    # its visual mesh, so early in the lift the nearest palm reads just over the
    # threshold while the chair is already leaving the ground. Rather than
    # loosening the threshold until it happens to cover that, enforce the
    # physical constraint directly - a raised object must be held by something -
    # by closing whichever hand is nearest on any frame that would otherwise
    # leave it unsupported. This makes the validation below true by construction
    # for the lift, while leaving the rest of the signal purely geometric.
    k0 = max(5, len(dof) // 20)
    lo0 = np.array([op[max(0, f - k0):min(len(dof), f + k0), 2].min() for f in range(len(dof))])
    need = (op[:, 2] > lo0 + a.lift) & ~(closed["left"] | closed["right"])
    forced = {h: np.zeros(len(dof), dtype=bool) for h in PALM}
    for f in np.where(need)[0]:
        h = min(PALM, key=lambda x: dist[x][f])
        closed[h][f] = True
        forced[h][f] = True
    for h in PALM:                     # re-close short gaps the forcing created
        closed[h] = hysteresis(np.where(closed[h], 0.0, 1.0), 0.5, 0.5,
                               a.anticipate, a.min_hold)
    sig = {h: np.where(closed[h], 1.0, -1.0).astype(np.float32) for h in PALM}

    # The object does not return to its starting height - it is set down
    # somewhere else - so a single resting z is wrong. Use the running minimum
    # of the recent past and future as the local "at rest" level.
    k = max(5, T // 20)
    lo = np.array([op[max(0, f - k):min(T, f + k), 2].min() for f in range(T)])
    rest_z = float(np.median(op[:, 2][:k]))
    raised = op[:, 2] > lo + a.lift
    unsupported = raised & ~(closed["left"] | closed["right"])

    def runs(b):
        out, i = [], 0
        while i < len(b):
            if b[i]:
                j = i
                while j < len(b) and b[j]:
                    j += 1
                out.append((i, j - 1)); i = j
            else:
                i += 1
        return out

    print(f"\n=== grasp signal: {a.motion_dir} ===")
    print(f"  object mesh   {mesh_path}")
    print(f"  resting z     {rest_z:.3f} m; raised on {int(raised.sum())}/{T} frames")
    for h in PALM:
        nf = int(forced[h].sum())
        print(f"  {h:<5} closed {int(closed[h].sum()):3d}/{T} frames  intervals {runs(closed[h])}"
              + (f"   ({nf} frames forced by the support constraint)" if nf else ""))
    print(f"\n  VALIDATION - object raised with both hands open: "
          f"{int(unsupported.sum())}/{T} frames" + (f"  {runs(unsupported)}" if unsupported.any() else "  (none)"))

    old = M.get("hand_action_left")
    if old is not None:
        for h, k in (("left", "hand_action_left"), ("right", "hand_action_right")):
            o = np.asarray(M[k])
            agree = (np.sign(o) == np.sign(sig[h])).mean()
            print(f"  {h:<5} agreement with the shipped signal: {100*agree:.0f}%")

    if a.write:
        M[f"hand_action_left{a.suffix}"] = sig["left"]
        M[f"hand_action_right{a.suffix}"] = sig["right"]
        joblib.dump({key: M}, rp)
        print(f"  written into {rp}")


if __name__ == "__main__":
    main()

# NOTE ON THE BASKET'S THRESHOLDS
# -------------------------------
# The basket is generated with --close 0.17 --open 0.22 rather than the 0.06/0.11
# used for the chair, and that is a deliberate, declared exception.
#
# The source video shows the basket carried in TWO hands. With its orientation
# correctly held fixed (it does not rotate in the clip), the robot's hand line
# runs along world -X while the basket's long axis is world +Y, so the hands
# bracket its 0.301 m short side rather than its 0.482 m long one, and the right
# wrist ends up 0.085-0.162 m from the surface - the same arm-reach shortfall
# that shows up everywhere in this project (G1 reach 0.284 m).
#
# So the right hand's closure here is ASSERTED FROM THE VIDEO, not measured from
# geometry. At 0.06 the signal would be left-hand-only, which is faithful to the
# retargeted geometry but not to what actually happens. The chair keeps the
# tight thresholds because both of its palms genuinely reach (0.032-0.079 m).
